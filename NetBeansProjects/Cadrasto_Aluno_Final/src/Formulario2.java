    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {
        int linha = jTbl_pessoas.getSelectedRow();
    
    if (linha == -1) {
        JOptionPane.showMessageDialog(
            null,
            "Selecione uma pessoa para excluir."
        );
        return;
    }
    
    int opcao = JOptionPane.showConfirmDialog(
        null,
        "Tem certeza que deseja excluir este registro?",
        "Confirmação de Exclusão",
        JOptionPane.YES_NO_OPTION
    );
    
    if (opcao == JOptionPane.YES_OPTION) {
        listaAlunos.remove(linha);
        
        arquivo.gravaArquivo();
        carregarTabela();
        limparCampos();
        
        JOptionPane.showMessageDialog(
            null,
            "Registro excluído com sucesso!"
        );
    }
    }

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {
        int linha = jTbl_pessoas.getSelectedRow();
    
    if (linha == -1) {
        JOptionPane.showMessageDialog(
            null,
            "Selecione uma pessoa para editar."
        );
        return;
    }
    
    linhaEdicao = linha;
    Aluno a = listaAlunos.get(linha);
    
    txtNome.setText(a.nome);
    jTextCurso.setText(a.curso);
    TextMatricula.setText(a.matricula);
    TextCpf.setText(a.cpf);
    jTextNasc.setText(a.dataNascimento);
    cmb_estado.setSelectedItem(a.estado);
    jTextCep.setText(a.cep);
    jTextEnde.setText(a.endereço);
    jTextTelefone.setText(a.telefone);
    
    if (a.sexo == 'M') {
        rdoMasculino.setSelected(true);
    } else {
        rdoFeminino.setSelected(true);
        }
    }

    private void limparCampos() {
        txtNome.setText("");
        jTextCurso.setText("");
        TextMatricula.setText("");
        TextCpf.setText("");
        jTextNasc.setText("");
        jTextTelefone.setText("");
        jTextEnde.setText("");
        jTextCep.setText("");
        btnGrpSexo.clearSelection();
        cmb_estado.setSelectedIndex(0);
    }

