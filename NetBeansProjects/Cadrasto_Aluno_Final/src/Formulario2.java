    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if (rdoMasculino.isSelected()) {
            sexo = 'M';
        } else if (rdoFeminino.isSelected()) {
            sexo = 'F';
        } else {
            JOptionPane.showMessageDialog(null, "Selecione o sexo do aluno", "Erro", JOptionPane.ERROR_MESSAGE);
            return;
        }

        String estado = cmb_estado.getSelectedItem() + "";

        // Instancia Aluno na ordem exata dos 10 parâmetros:
        // (nome, dataNascimento, sexo, matricula, curso, cpf, endereço, cep, estado, telefone)
        Aluno a = new Aluno(
            txtNome.getText(),
            jTextNasc.getText(),
            sexo,
            TextMatricula.getText(),
            jTextCurso.getText(),
            TextCpf.getText(),
            jTextEnde.getText(),
            jTextCep.getText(),
            estado,
            jTextTelefone.getText()
        );

        listaAlunos.add(a);
        arquivo.gravaArquivo();
        carregarTabela();
        limparCampos();
    }//GEN-LAST:event_btnSalvarActionPerformed

