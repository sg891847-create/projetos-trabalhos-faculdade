    private void Bnt_AtualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bnt_AtualizarActionPerformed
        if (TextF_idOcult.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Consulte uma pessoa antes de tentar atualizar!");
        return;
    }

    String sexo = null;
    if (Rdo_M.isSelected()) {
        sexo = "M";
    } else if (Rdo_F.isSelected()) {
        sexo = "F";
    }

    Pessoa p = new Pessoa();
    p.setId(Integer.parseInt(TextF_idOcult.getText()));
    p.setNome(TextF_Nome.getText());
    p.setSexo(sexo);
    p.setIdioma(Cmb_Idioma.getSelectedItem().toString());

    PessoaDao pDAO = new PessoaDao();
    pDAO.editar(p);

    JOptionPane.showMessageDialog(this, "Registro atualizado com sucesso!");
    limparFormulario();
    }//GEN-LAST:event_Bnt_AtualizarActionPerformed

