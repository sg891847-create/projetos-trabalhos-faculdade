    private void Bnt_ConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Bnt_ConsultarActionPerformed
       try {
        int idPessoa = Integer.parseInt(TextF_id.getText());
        PessoaDao pDAO = new PessoaDao();
        Pessoa p = pDAO.getPessoa(idPessoa);
        
        if (p == null) {
            limparFormulario();
            JOptionPane.showMessageDialog(this, "Pessoa não encontrada!");
        } else {
            TextF_idOcult.setText(String.valueOf(p.getId()));
            TextF_Nome.setText(p.getNome());
            
            if ("M".equalsIgnoreCase(p.getSexo())) {
                Rdo_M.setSelected(true);
            } else if ("F".equalsIgnoreCase(p.getSexo())) {
                Rdo_F.setSelected(true);
            }
            
            Cmb_Idioma.setSelectedItem(p.getIdioma());
        }
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Informe um ID válido para consulta!");
    }
    }//GEN-LAST:event_Bnt_ConsultarActionPerformed

    private void BntExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BntExcluirActionPerformed
       if (TextF_idOcult.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Consulte uma pessoa antes de excluir!");
        return;
    }

    int resposta = JOptionPane.showConfirmDialog(
        this, 
        "Deseja realmente excluir?", 
        "Exclusão", 
        JOptionPane.YES_NO_OPTION
    );

    if (resposta == JOptionPane.YES_OPTION) {
        int id = Integer.parseInt(TextF_idOcult.getText());
        PessoaDao pDAO = new PessoaDao();
        pDAO.excluir(id);

        JOptionPane.showMessageDialog(this, "Pessoa excluída com sucesso!");
        limparFormulario();
    }
    }//GEN-LAST:event_BntExcluirActionPerformed

